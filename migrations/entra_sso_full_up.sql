-- ── 4. Cleanup function — removes expired sso_state rows ─────────────────────
--
-- Called inline from /api/entra-callback.ts after validating each request.
-- Also scheduled below to run hourly so the table never bloats.

CREATE OR REPLACE FUNCTION cleanup_expired_sso_state()
RETURNS void
LANGUAGE sql
SECURITY DEFINER
AS $$
  DELETE FROM sso_state WHERE expires_at < NOW();
$$;

